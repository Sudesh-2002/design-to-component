"use client";

import { useRef, useState } from "react";
import dynamic from "next/dynamic";
import {
  AlertTriangle,
  AlignLeft,
  Check,
  Copy,
  RotateCcw,
  XCircle,
} from "lucide-react";
import type { CodeEditorInstance } from "@/components/panels/CodeEditor";
import { usePlayground } from "@/store/playground";

const CodeEditor = dynamic(
  () => import("@/components/panels/CodeEditor").then((m) => m.CodeEditor),
  {
    ssr: false,
    loading: () => (
      <p className="p-3 text-sm text-neutral-500">Loading editor…</p>
    ),
  }
);

const toolbarButton =
  "flex items-center gap-1.5 rounded-md px-2 py-1 text-xs text-neutral-400 transition hover:bg-neutral-800 hover:text-neutral-100 disabled:cursor-not-allowed disabled:opacity-40 disabled:hover:bg-transparent disabled:hover:text-neutral-400";

export function CodePanel() {
  const code = usePlayground((s) => s.code);
  const generatedCode = usePlayground((s) => s.generatedCode);
  const raw = usePlayground((s) => s.raw);
  const status = usePlayground((s) => s.status);
  const error = usePlayground((s) => s.error);
  const issues = usePlayground((s) => s.issues);
  const setCode = usePlayground((s) => s.setCode);
  const resetCode = usePlayground((s) => s.resetCode);

  const editorRef = useRef<CodeEditorInstance | null>(null);
  const [copied, setCopied] = useState(false);

  const isGenerating = status === "loading" || status === "streaming";
  const hasCode = code.trim().length > 0;
  const isEdited = generatedCode !== "" && code !== generatedCode;

  async function copy() {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
    }
  }

  function format() {
    editorRef.current?.getAction("editor.action.formatDocument")?.run();
  }

  return (
    <div className="flex h-full min-h-[400px] flex-col gap-2">
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2 text-xs text-neutral-500">
          <span>component.tsx</span>
          {isEdited && !isGenerating && (
            <span className="rounded-full border border-neutral-800 px-2 py-0.5 text-neutral-400">
              edited
            </span>
          )}
        </div>
        <div className="flex gap-1">
          <button
            type="button"
            onClick={format}
            disabled={!hasCode || isGenerating}
            title="Format (Ctrl+S)"
            className={toolbarButton}
          >
            <AlignLeft className="h-3.5 w-3.5" />
            Format
          </button>
          <button
            type="button"
            onClick={resetCode}
            disabled={!isEdited || isGenerating}
            title="Restore the version generated by the model"
            className={toolbarButton}
          >
            <RotateCcw className="h-3.5 w-3.5" />
            Reset
          </button>
          <button
            type="button"
            onClick={copy}
            disabled={!hasCode}
            className={toolbarButton}
          >
            {copied ? (
              <Check className="h-3.5 w-3.5 text-emerald-400" />
            ) : (
              <Copy className="h-3.5 w-3.5" />
            )}
            {copied ? "Copied" : "Copy"}
          </button>
        </div>
      </div>

      {status === "error" && error && (
        <p className="rounded-lg border border-red-900 bg-red-950/50 p-3 text-sm text-red-300">
          {error}
        </p>
      )}

      {issues.length > 0 && !isGenerating && (
        <ul className="max-h-32 space-y-1.5 overflow-auto">
          {issues.map((issue, i) => (
            <li
              key={i}
              className={
                issue.level === "error"
                  ? "flex items-start gap-2 rounded-lg border border-red-900/60 bg-red-950/40 p-2.5 text-xs text-red-300"
                  : "flex items-start gap-2 rounded-lg border border-amber-900/60 bg-amber-950/30 p-2.5 text-xs text-amber-300"
              }
            >
              {issue.level === "error" ? (
                <XCircle className="mt-0.5 h-3.5 w-3.5 shrink-0" />
              ) : (
                <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" />
              )}
              <span>{issue.message}</span>
            </li>
          ))}
        </ul>
      )}

      <div className="relative min-h-[240px] flex-1 overflow-hidden rounded-lg border border-neutral-800 bg-neutral-950">
        <CodeEditor
          value={code}
          readOnly={isGenerating}
          onChange={setCode}
          onReady={(editor) => {
            editorRef.current = editor;
          }}
        />

        {!hasCode && !isGenerating && (
          <p className="pointer-events-none absolute left-14 right-4 top-3 text-sm text-neutral-600">
            Generated code appears here. You can also paste your own component
            (it needs a default export).
          </p>
        )}
      </div>

      {raw && !isGenerating && (
        <details className="text-xs text-neutral-600">
          <summary className="cursor-pointer hover:text-neutral-400">
            Raw model output
          </summary>
          <pre className="mt-2 max-h-48 overflow-auto whitespace-pre-wrap break-words font-mono">
            {raw}
          </pre>
        </details>
      )}
    </div>
  );
}